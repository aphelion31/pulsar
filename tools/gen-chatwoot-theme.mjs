#!/usr/bin/env node
// Generates web/app/chatwoot-theme.css from Chatwoot's design tokens so Pulsar's Tailwind v4 classes
// (bg-n-slate-3, text-n-blue-11, border-n-weak, ...) resolve to the same values as Chatwoot.
// Sources: chatwoot/theme/colors.js (the `n` palette) and _next-colors.scss (CSS vars, light + .dark).
// Usage: node tools/gen-chatwoot-theme.mjs ../chatwoot > web/app/chatwoot-theme.css
import { readFileSync } from 'node:fs';

const cw = process.argv[2] || '../chatwoot';
const js = readFileSync(`${cw}/theme/colors.js`, 'utf8');
const scss = readFileSync(`${cw}/app/javascript/dashboard/assets/scss/_next-colors.scss`, 'utf8');

// 1. CSS variables: keep :root and .dark blocks verbatim (minus scss comments).
const vars = scss
  .replace(/\/\/[^\n]*/g, '')
  .replace(/@layer base\s*{/, '')
  .replace(/}\s*$/, '')
  .trim();

// 2. The `n:` object -> flat token list. Walk it with a tiny brace parser.
const start = js.search(/\n\s+n: {/);
let i = js.indexOf('{', start), depth = 0, end = i;
for (; end < js.length; end++) {
  if (js[end] === '{') depth++;
  else if (js[end] === '}' && --depth === 0) break;
}
const body = js.slice(i + 1, end).replace(/\/\/[^\n]*/g, '');
const out = [];
const path = [];
for (const raw of body.split('\n')) {
  const line = raw.trim();
  if (!line) continue;
  let m;
  if ((m = line.match(/^'?([\w-]+)'?\s*:\s*{\s*$/))) { path.push(m[1]); continue; }
  if (/^},?$/.test(line)) { path.pop(); continue; }
  if ((m = line.match(/^'?([\w-]+)'?\s*:\s*'([^']+)',?$/))) {
    const name = [...path, m[1]].join('-');
    // Tailwind v3 `<alpha-value>` placeholder: v4 handles opacity via color-mix, so use the opaque value.
    const value = m[2].replace(' / <alpha-value>', '');
    out.push(`  --color-n-${name}: ${value};`);
  }
}

console.log(`/* Generated by tools/gen-chatwoot-theme.mjs from Chatwoot's theme. Do not edit by hand. */
@layer base {
${vars}
}

@theme {
${out.join('\n')}
}
`);
