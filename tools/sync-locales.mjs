  am: "አማርኛ",
  ar: "العربية",
  az: "Azərbaycanca",
  bg: "Български",
  bn: "বাংলা",
  ca: "Català",
  cs: "Čeština",
  da: "Dansk",
  de: "Deutsch",
  el: "Ελληνικά",
  es: "Español",
  et: "Eesti",
  fa: "فارسی",
  fi: "Suomi",
  fr: "Français",
  he: "עברית",
  hi: "हिन्दी",
